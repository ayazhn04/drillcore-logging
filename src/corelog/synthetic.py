"""Small synthetic dataset in the exact RA format (photos + rows.csv + log_intervals.csv).

Used by tests and `corelog smoke-test`. Each class has a distinct colour and texture
orientation so models can learn something within a few CPU steps. Photos imitate
core trays: wooden background with horizontal core rows; one photo per hole is
stored right-to-left to exercise `direction`.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from .images import save_rgb

MARKER = "SYNTHETIC_DATASET.txt"
# Class names are deliberately non-geological (syn_*) so synthetic results can never be
# mistaken for real lithology classification results.
CLASSES = {  # code: (model class, rgb, texture angle deg, texture freq cyc/px)
    "S1": ("syn_class_1", (205, 200, 185), 0, 0.10),
    "S2": ("syn_class_2", (150, 60, 50), 45, 0.15),
    "S3": ("syn_class_3", (180, 130, 110), 90, 0.12),
    "NC": ("non_core", (95, 70, 40), 135, 0.25),
}


def _texture(code: str, h: int, w: int, rng) -> np.ndarray:
    _, rgb, ang, f = CLASSES[code]
    y, x = np.mgrid[0:h, 0:w]
    a = np.deg2rad(ang)
    t = 0.25 * np.sin(2 * np.pi * f * (x * np.cos(a) + y * np.sin(a)) + rng.uniform(0, 6.28))
    img = np.stack([c * (1 + t) for c in rgb], -1) + rng.normal(0, 6, (h, w, 3))
    return img


def make_dataset(root: str | Path, holes=("SYN_A", "SYN_B", "SYN_C", "SYN_D"), photos_per_hole: int = 3,
                 rows_per_photo: int = 3, row_len_m: float = 1.2, px_per_m: int = 1000,
                 row_h: int = 60, seed: int = 0) -> dict:
    rng = np.random.default_rng(seed)
    root = Path(root)
    (root / "photos").mkdir(parents=True, exist_ok=True)
    (root / "manifests").mkdir(parents=True, exist_ok=True)
    codes = list(CLASSES)
    rows, logs = [], []
    row_w = int(row_len_m * px_per_m)
    for hi, hole in enumerate(holes):
        top = 100.0 + 10 * hi
        total = photos_per_hole * rows_per_photo * row_len_m
        d, ints = top, []
        while d < top + total:
            L = float(rng.choice([0.55, 0.85, 1.25, 1.7]))  # not multiples of the tile length -> contact tiles
            ints.append((d, min(d + L, top + total), codes[int(rng.integers(len(codes)))]))
            d += L
        logs += [{"hole_id": hole, "depth_from_m": round(a, 3), "depth_to_m": round(b, 3), "lithology_code": c}
                 for a, b, c in ints]

        def code_at(z):
            for a, b, c in ints:
                if a <= z < b:
                    return c
            return ints[-1][2]

        for p in range(photos_per_hole):
            pid = f"{hole}_P{p + 1:02d}"
            H, W = rows_per_photo * (row_h + 40) + 40, row_w + 120
            photo = np.full((H, W, 3), (120, 85, 50), float) + rng.normal(0, 5, (H, W, 3))
            rtl = p == photos_per_hole - 1
            for r in range(rows_per_photo):
                d0 = top + (p * rows_per_photo + r) * row_len_m
                strip = np.zeros((row_h, row_w, 3))
                for x0 in range(0, row_w, 50):  # paint per 5 cm column according to the log
                    strip[:, x0:x0 + 50] = _texture(code_at(d0 + (x0 + 25) / px_per_m), row_h, min(50, row_w - x0), rng)
                if rtl:
                    strip = strip[:, ::-1]
                y0, x0 = 40 + r * (row_h + 40), 60
                photo[y0:y0 + row_h, x0:x0 + row_w] = strip
                rows.append({"hole_id": hole, "photo_id": pid, "image_path": f"photos/{pid}.png",
                             "row_id": str(r + 1), "depth_from_m": round(d0, 3),
                             "depth_to_m": round(d0 + row_len_m, 3), "x0": x0, "y0": y0,
                             "x1": x0 + row_w, "y1": y0 + row_h, "direction": "rtl" if rtl else "ltr",
                             "exclude": 0, "notes": ""})
            save_rgb(np.clip(photo, 0, 255).astype(np.uint8), root / "photos" / f"{pid}.png")
    (root / MARKER).write_text("SYNTHETIC test dataset generated by corelog.synthetic.\n"
                               "Results computed on it are NOT geological classification results.\n")
    pd.DataFrame(rows).to_csv(root / "manifests" / "rows.csv", index=False)
    pd.DataFrame(logs).to_csv(root / "manifests" / "log_intervals.csv", index=False)
    return {"root": root, "n_rows": len(rows), "n_intervals": len(logs)}
