"""Small synthetic dataset in the exact RA format (photos + rows.csv + log_intervals.csv).

Used by tests and `corelog smoke-test`. Each class has a distinct colour and texture
orientation so models can learn something within a few CPU steps. Photos imitate
core trays: wooden background with horizontal core rows; one photo per hole is
stored right-to-left to exercise `direction`.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from .images import save_rgb

MARKER = "SYNTHETIC_DATASET.txt"
# Class names are deliberately non-geological (syn_*) so synthetic results can never be
# mistaken for real lithology classification results.
CLASSES = {  # code: (model class, rgb, texture angle deg, texture freq cyc/px)
    "S1": ("syn_class_1", (205, 200, 185), 0, 0.10),
    "S2": ("syn_class_2", (150, 60, 50), 45, 0.15),
    "S3": ("syn_class_3", (180, 130, 110), 90, 0.12),
    "NC": ("non_core", (95, 70, 40), 135, 0.25),
}


def _texture(code: str, h: int, w: int, rng) -> np.ndarray:
    _, rgb, ang, f = CLASSES[code]
    y, x = np.mgrid[0:h, 0:w]
    a = np.deg2rad(ang)
    t = 0.25 * np.sin(2 * np.pi * f * (x * np.cos(a) + y * np.sin(a)) + rng.uniform(0, 6.28))
    img = np.stack([c * (1 + t) for c in rgb], -1) + rng.normal(0, 6, (h, w, 3))
    return img


def make_dataset(root: str | Path, holes=("SYN_A", "SYN_B", "SYN_C", "SYN_D"), photos_per_hole: int = 3,
                 rows_per_photo: int = 3, row_len_m: float = 1.2, px_per_m: int = 1000,
                 row_h: int = 60, seed: int = 0) -> dict:
    rng = np.random.default_rng(seed)
    root = Path(root)
    (root / "photos").mkdir(parents=True, exist_ok=True)
    (root / "manifests").mkdir(parents=True, exist_ok=True)
    codes = list(CLASSES)
    rows, logs = [], []
    row_w = int(row_len_m * px_per_m)
    for hi, hole in enumerate(holes):
        top = 100.0 + 10 * hi
        total = photos_per_hole * rows_per_photo * row_len_m
        d, ints = top, []
        while d < top + total:
            L = float(rng.choice([0.55, 0.85, 1.25, 1.7]))  # not multiples of the tile length -> contact tiles
            ints.append((d, min(d + L, top + total), codes[int(rng.integers(len(codes)))]))
            d += L
        logs += [{"hole_id": hole, "depth_from_m": round(a, 3), "depth_to_m": round(b, 3), "lithology_code": c}
                 for a, b, c in ints]

        def code_at(z):
            for a, b, c in ints:
                if a <= z < b:
                    return c
            return ints[-1][2]

        for p in range(photos_per_hole):
            pid = f"{hole}_P{p + 1:02d}"
            H, W = rows_per_photo * (row_h + 40) + 40, row_w + 120
            photo = np.full((H, W, 3), (120, 85, 50), float) + rng.normal(0, 5, (H, W, 3))
            rtl = p == photos_per_hole - 1
            for r in range(rows_per_photo):
                d0 = top + (p * rows_per_photo + r) * row_len_m
                strip = np.zeros((row_h, row_w, 3))
                for x0 in range(0, row_w, 50):  # paint per 5 cm column according to the log
                    strip[:, x0:x0 + 50] = _texture(code_at(d0 + (x0 + 25) / px_per_m), row_h, min(50, row_w - x0), rng)
                if rtl:
                    strip = strip[:, ::-1]
                y0, x0 = 40 + r * (row_h + 40), 60
                photo[y0:y0 + row_h, x0:x0 + row_w] = strip
                rows.append({"hole_id": hole, "photo_id": pid, "image_path": f"photos/{pid}.png",
                             "row_id": str(r + 1), "depth_from_m": round(d0, 3),
                             "depth_to_m": round(d0 + row_len_m, 3), "x0": x0, "y0": y0,
                             "x1": x0 + row_w, "y1": y0 + row_h, "direction": "rtl" if rtl else "ltr",
                             "exclude": 0, "notes": ""})
            save_rgb(np.clip(photo, 0, 255).astype(np.uint8), root / "photos" / f"{pid}.png")
    (root / MARKER).write_text("SYNTHETIC test dataset generated by corelog.synthetic.\n"
                               "Results computed on it are NOT geological classification results.\n")
    pd.DataFrame(rows).to_csv(root / "manifests" / "rows.csv", index=False)
    pd.DataFrame(logs).to_csv(root / "manifests" / "log_intervals.csv", index=False)
    return {"root": root, "n_rows": len(rows), "n_intervals": len(logs)}


def make_rock_only_dataset(root: str | Path, holes=("SYN_A", "SYN_B"), boxes_per_hole: int = 4,
                           rows_per_box: int = 4, box_len_m: float = 3.6, px_per_m: int = 400,
                           row_h: int = 80, seed: int = 0, bom: bool = True) -> dict:
    """Synthetic copy of a *rock-only, pre-cropped* delivery (one PNG per core row).

    Mirrors the layout: photos/<hole>/<row>.png (8-bit RGB, background exactly black),
    masks/<hole>/<row>_mask.png (255 = rock), rows.csv with EMPTY x0..y1, box intervals
    split over rows in proportion to core length, a partly filled last box (its last rows
    omitted), log_intervals.csv + log_weathering.csv (+ BOM, as Excel writes them), and
    core broken into pieces with black gaps. Classes S1..S3 only (no non-core class).
    """
    rng = np.random.default_rng(seed)
    root = Path(root)
    (root / "manifests").mkdir(parents=True, exist_ok=True)
    codes = ["S1", "S2", "S3"]
    rows, logs, weath = [], [], []
    for hi, hole in enumerate(holes):
        top = 20.0 + 5 * hi
        bottom = top + boxes_per_hole * box_len_m
        d, ints = top, []
        k = hi  # different class order per hole, every class present in every hole
        while d < bottom - 1e-9:
            L = float(rng.choice([1.3, 1.9, 2.6, 3.1]))
            ints.append((round(d, 3), round(min(d + L, bottom), 3), codes[k % 3]))
            d, k = d + L, k + 1
        logs += [{"hole_id": hole, "depth_from_m": a, "depth_to_m": b, "lithology_code": c,
                  "description": "синтетика"} for a, b, c in ints]
        weath += [{"hole_id": hole, "depth_from_m": a, "depth_to_m": b, "lithology_code": f"W{1 + j % 2}",
                   "description": ""} for j, (a, b, _) in enumerate(ints)]

        def code_at(z):
            for a, b, c in ints:
                if a <= z < b:
                    return c
            return ints[-1][2]

        for b in range(boxes_per_hole):
            b0 = top + b * box_len_m
            last = b == boxes_per_hole - 1
            fill = [1.0] * rows_per_box if not last else [1.0, 0.45] + [0.0] * (rows_per_box - 2)
            core_len = [f * box_len_m / rows_per_box for f in fill]
            d = b0
            for r, L in enumerate(core_len):
                if L <= 0:
                    continue  # empty rows are left out of rows.csv, as in the delivery
                span = box_len_m * L / sum(core_len)  # proportional split of the box interval
                w = int(round(L * px_per_m)) + 16
                img = np.zeros((row_h, w, 3))
                mask = np.zeros((row_h, w), bool)
                x, yc, rad = 8, row_h // 2, int(row_h * 0.35)
                while x < w - 8:  # pieces of core separated by black gaps
                    pl = int(rng.integers(25, 120))
                    x1 = min(x + pl, w - 8)
                    mask[yc - rad:yc + rad, x:x1] = True
                    x = x1 + int(rng.integers(2, 10))
                for x0 in range(0, w, 20):
                    z = d + span * (x0 + 10) / w
                    img[:, x0:x0 + 20] = _texture(code_at(z), row_h, min(20, w - x0), rng)
                img = np.clip(img, 0, 255).astype(np.uint8)
                img[~mask] = 0
                name = f"{hole}_Box{b + 1:02d}_row{r + 1}"
                ip, mp = f"photos/{hole}/{name}.png", f"masks/{hole}/{name}_mask.png"
                save_rgb(img, root / ip)
                save_rgb(np.repeat((mask * 255).astype(np.uint8)[..., None], 3, -1), root / mp)
                rows.append({"hole_id": hole, "photo_id": f"{hole}_Box{b + 1:02d}", "image_path": ip,
                             "row_id": str(r + 1), "depth_from_m": round(d, 3), "depth_to_m": round(d + span, 3),
                             "x0": "", "y0": "", "x1": "", "y1": "", "direction": "ltr", "exclude": 0,
                             "notes": "box interval split by core length"})
                d += span
    (root / MARKER).write_text("SYNTHETIC rock-only test dataset generated by corelog.synthetic.\n"
                               "Results computed on it are NOT geological classification results.\n")
    enc = "utf-8-sig" if bom else "utf-8"
    pd.DataFrame(rows).to_csv(root / "manifests" / "rows.csv", index=False, encoding=enc)
    pd.DataFrame(logs).to_csv(root / "manifests" / "log_intervals.csv", index=False, encoding=enc)
    pd.DataFrame(weath).to_csv(root / "manifests" / "log_weathering.csv", index=False, encoding=enc)
    return {"root": root, "n_rows": len(rows), "n_intervals": len(logs)}
